// Writes supabase/functions/_shared/pushTexts.ts from the app's own
// translations, so push notifications use exactly the texts the in-app
// bell shows. Run after changing shell.json "notifications" or leave.json
// "types": node scripts/gen-push-texts.mjs (a test fails if it is stale).
import { readFileSync, writeFileSync } from "node:fs";

export const LANGUAGES = ["ar", "en", "de", "fr", "it"];

export function buildPushTexts(root = ".") {
  const texts = {};
  for (const language of LANGUAGES) {
    const shell = JSON.parse(readFileSync(`${root}/src/i18n/locales/${language}/shell.json`, "utf8"));
    const leave = JSON.parse(readFileSync(`${root}/src/i18n/locales/${language}/leave.json`, "utf8"));
    texts[language] = { notifications: shell.notifications, leaveTypes: leave.types };
  }
  return texts;
}

export function renderPushTextsModule(texts) {
  return `// GENERATED by scripts/gen-push-texts.mjs from src/i18n/locales - do not edit by hand.
// The in-app notification texts (shell.json "notifications", leave.json "types"), for push notifications.
// deno-lint-ignore-file
export const PUSH_TEXTS: Record<string, { notifications: Record<string, any>; leaveTypes: Record<string, string> }> = ${JSON.stringify(texts, null, 2)};
`;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("gen-push-texts.mjs")) {
  writeFileSync("supabase/functions/_shared/pushTexts.ts", renderPushTextsModule(buildPushTexts()));
  console.log("supabase/functions/_shared/pushTexts.ts written");
}
